# Generate the Java opcode constants class for the CPython version running this script
#
# Usage: python opcode_gen.py [dstdir]
#
# The class written is named OpcodeNNN (e.g. Opcode315 for CPython 3.15)
# in package org.python.core. With dstdir (the root of a Java source
# tree) it is written to dstdir/org/python/core/OpcodeNNN.java,
# otherwise to standard output. The Gradle build runs this (task
# core:generateOpcodes) with the CPython whose byte code the interpreter
# supports, writing to core/build/generated/sources/opcodes/java/main.
#
# Everything is taken from the opcode and dis modules, so that a move
# to a new version of CPython is (as far as the constants go) a re-run.
#
# Specialized ("quickened") and instrumented opcodes are deliberately
# omitted: CPython only creates them at run time, so they never appear
# in the code objects we load (from .pyc files or marshal).

import os, sys
import opcode, dis

VER = f"{sys.version_info.major}{sys.version_info.minor}"
CLASS = f"Opcode{VER}"
VERSION = f"{sys.version_info.major}.{sys.version_info.minor}"


def opcodes():
    "Real (not pseudo, not instrumented) opcodes in numerical order"
    ops = [(v, k) for k, v in opcode.opmap.items()
           if v < 256 and not k.startswith("INSTRUMENTED_")]
    return sorted(ops)


def generate(out):
    p = lambda s="": print(s, file=out)

    p("// Copyright (c)2026 Jython Developers.")
    p("// Licensed to PSF under a contributor agreement.")
    p("package org.python.core;")
    p()
    p("// Generated by build-tools/python/tool/opcode_gen.py (Gradle task core:generateOpcodes)")
    p(f"// from CPython {sys.version.split()[0]}. Do not edit by hand.")
    p("// Specialized and instrumented opcodes are omitted: they never")
    p("// appear in code loaded from .pyc files or marshal.")
    p()
    p(f"/** Constants for opcodes taken from CPython {VERSION} {{@code opcode}} module. */")
    p(f"class {CLASS} {{")
    p()
    p(f"    private {CLASS}() {{}} // no instances")
    p()
    p("    /* Instruction opcodes for compiled code */")
    p()
    for v, k in opcodes():
        p(f"    /** CPython opcode {k} */")
        p(f"    static final int {k} = {v};")
    p()
    p("    /** Opcodes at or above this value use their argument. */")
    p(f"    static final int HAVE_ARGUMENT = {opcode.HAVE_ARGUMENT};")
    p()

    p("    // An encoding of binary operations used only by BINARY_OP")
    p()
    for i, (name, sym) in enumerate(dis._nb_ops):
        p(f"    /** Encoding of {sym} used in BINARY_OP opcode. */")
        p(f"    static final int {name} = {i};")
    p()

    # From 3.13 the comparison is in the upper bits of the argument
    cmp_shifted = sys.version_info >= (3, 13)
    if cmp_shifted:
        p("    // Comparisons encoded in COMPARE_OP (as oparg >> 5)")
    else:
        p("    // Comparisons encoded in COMPARE_OP (as oparg)")
    p()
    for i, sym in enumerate(dis.cmp_op):
        p(f"    /** Encoding of {sym} in COMPARE_OP opcode. */")
        p(f"    static final int CMP_{i_name(sym)} = {i};")
    if cmp_shifted:
        p("    /** Shift to extract comparison from COMPARE_OP argument. */")
        p("    static final int CMP_SHIFT = 5;")
        p("    /** Flag in COMPARE_OP argument: convert result to bool. */")
        p("    static final int CMP_TO_BOOL = 16;")
    p()

    if hasattr(dis, "_intrinsic_1_descs"):  # 3.12+
        p("    // Operations encoded in CALL_INTRINSIC_1 and CALL_INTRINSIC_2")
        p()
        for i, name in enumerate(dis._intrinsic_1_descs):
            p(f"    /** Encoding of {name} in CALL_INTRINSIC_1 opcode. */")
            p(f"    static final int {name} = {i};")
        for i, name in enumerate(dis._intrinsic_2_descs):
            p(f"    /** Encoding of {name} in CALL_INTRINSIC_2 opcode. */")
            p(f"    static final int {name} = {i};")
        p()

    if hasattr(dis, "_common_constants"):  # 3.14+
        p("    // Constants indexed by LOAD_COMMON_CONSTANT")
        p()
        for i, c in enumerate(dis._common_constants):
            p(f"    /** Index of {common_repr(c)} in LOAD_COMMON_CONSTANT. */")
            p(f"    static final int COMMON_{common_name(c)} = {i};")
        p(f"    /** Number of LOAD_COMMON_CONSTANT constants. */")
        p(f"    static final int COMMON_CONSTANT_COUNT = {len(dis._common_constants)};")
        p()

    p("    /*")
    p("     * Various CPython opcodes are followed by an in-line cache, which")
    p("     * is zero in the byte code initially. We do not implement this")
    p("     * cache, but end those instructions with an advance of the IP of")
    p("     * the right size. Jumps are relative to the end of the cache.")
    p("     */")
    p()
    for k, n in inline_cache_entries():
        if n and k in opcode.opmap:
            p(f"    /** Cache following {k} opcode (words). */")
            p(f"    static final int INLINE_CACHE_ENTRIES_{k} = {n};")
    p("}")


def inline_cache_entries():
    "(name, size) of the in-line cache of each opcode, sorted by name"
    entries = opcode._inline_cache_entries
    if isinstance(entries, list):
        # Before 3.12 this is a list indexed by opcode
        entries = {opcode.opname[i]: n for i, n in enumerate(entries)}
    return sorted(entries.items())


def i_name(sym):
    return {"<": "LT", "<=": "LE", "==": "EQ", "!=": "NE", ">": "GT",
            ">=": "GE"}[sym]


def common_repr(c):
    if isinstance(c, type) or callable(c):
        return "{@code " + c.__name__ + "}"
    return "{@code " + repr(c) + "}"


def common_name(c):
    if isinstance(c, type) or callable(c):
        # AssertionError -> ASSERTION_ERROR, all -> ALL
        n = c.__name__
        return "".join("_" + ch if ch.isupper() and i else ch
                       for i, ch in enumerate(n)).upper()
    return {None: "NONE", "": "EMPTY_STR", True: "TRUE", False: "FALSE",
            -1: "MINUS_ONE"}[c]


# The version of CPython whose byte code the Jython interpreter executes
SUPPORTED_VERSION = (3, 11)

if __name__ == "__main__":
    if sys.version_info[:2] != SUPPORTED_VERSION:
        print(f"opcode_gen requires CPython "
              f"{'.'.join(map(str, SUPPORTED_VERSION))}, not {sys.version.split()[0]}"
              f" ({sys.executable})", file=sys.stderr)
        sys.exit(1)
    if len(sys.argv) > 1:
        pkgdir = os.path.join(sys.argv[1], "org", "python", "core")
        os.makedirs(pkgdir, exist_ok=True)
        dst = os.path.join(pkgdir, CLASS + ".java")
        with open(dst, "w", encoding="utf-8") as f:
            generate(f)
        print(f"  Generate: {dst}")
    else:
        generate(sys.stdout)
