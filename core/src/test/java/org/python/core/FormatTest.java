/**
 * Tests of formatting built-in types to string using their
 * {@code __format__} method (on which built-in method {@code format()}
 * relies).
 * <p>
 * Most of the examples here use values generated by a Python script and
 * placed in a Java array (of {@code Object}). We then create a stream
 * of JUnit arguments objects, each containing those values formatted by
 * a specified format string using the call {@code format(v, fmt)}.
 * <p>
 * A fragment of Python for translating values for the array and
 * arguments object is:<pre>
 * def java_literal(v):
 *     '''Print single value as Java literal'''
 *     if isinstance(v, bool):
 *         return repr(v).lower()
 *     elif isinstance(v, int):
 *         if 2**31 > v >= -2**31:
 *             return repr(v)
 *         else:
 *             return f'new BigInteger("{v!r:s}")'
 *     else: # float
 *         if math.isnan(v):
 *             return 'Double.NaN'
 *         elif math.isinf(v):
 *             if v > 0:
 *                 return 'Double.POSITIVE_INFINITY'
 *             else:
 *                 return 'Double.NEGATIVE_INFINITY'
 *         return repr(v)
 *
 * def gen_example(func_name, values, fmt):
 *     args = '", "'.join(format(v, fmt) for v in values)
 *     return f'{func_name}("{fmt:s}", "{args}"), //'
 * </pre>
 */
